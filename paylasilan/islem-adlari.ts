const SAYFA_GRUBU: Readonly<Record<string, string>> = {
  'sayfa.uretim-terminali': 'terminal',
  'sayfa.kuyruk': 'uretim-emirleri',
  'sayfa.cizelge': 'plan',
  'sayfa.matris': 'plan',
  'sayfa.mesai': 'vardiya',
  'sayfa.personel': 'kisiler',
  'sayfa.ik-islemlerim': 'ik',
};

const SAYFA_ADLARI = new Map<string, string>(SAYFALAR.map((s) => [s.islem, s.baslik]));

export function islemGrubu(islem: string): string {
  if (islem.startsWith('sayfa.')) return SAYFA_GRUBU[islem] ?? islem.slice('sayfa.'.length);
  return islem.split('.')[0] ?? islem;
}

export function islemAdi(islem: string): string {
  const sayfa = SAYFA_ADLARI.get(islem as SayfaIslemi);
  if (sayfa !== undefined) return `${sayfa} sayfasını görme`;
  return (ISLEM_ADLARI as Readonly<Record<string, string>>)[islem] ?? islem;
}

export function grupAdi(grup: string): string {
  return MODUL_ADLARI[grup] ?? SAYFA_ADLARI.get(`sayfa.${grup}` as SayfaIslemi) ?? grup;
}
