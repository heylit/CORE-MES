-- İşlem şartnamesi kütüphanesi (971 a, 972 a, 973 a): kaplama, boya, ısıl işlem, kaynak gibi işlemlerin ortak şartları rota modülünde,
-- hizmet kartından bağımsız. Rota adımı şartname seçer ve değer verir; iş emri açılınca yürürlükteki sürüm ve değerler emre sabitlenir.
-- Bütün tablolar yenidir; dolu tabloya dokunulmaz. Standart metni tutulmaz, yalnız numara ve kısa açıklama.

CREATE TABLE rota_islem_kategorisi (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kod text NOT NULL CONSTRAINT rota_islem_kategorisi_kod_bicimi CHECK (kod ~ '^[A-Z]{2,6}$'),
  ad text NOT NULL CONSTRAINT rota_islem_kategorisi_ad_dolu CHECK (btrim(ad) <> ''),
  sira int NOT NULL CONSTRAINT rota_islem_kategorisi_sira_pozitif CHECK (sira > 0),
  CONSTRAINT rota_islem_kategorisi_kod_tekil UNIQUE (kod)
);

CREATE TABLE rota_standart_atfi (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  numara text NOT NULL CONSTRAINT rota_standart_atfi_numara_dolu CHECK (btrim(numara) <> '' AND length(numara) <= 60),
  kisa_aciklama text NOT NULL CONSTRAINT rota_standart_atfi_aciklama_dolu CHECK (btrim(kisa_aciklama) <> '' AND length(kisa_aciklama) <= 200),
  CONSTRAINT rota_standart_atfi_numara_tekil UNIQUE (numara)
);

-- kaynak: varsayilan (kurulumla gelen kütüphane), firma (atölyenin kendi şartnamesi), musteri (müşteri şartnamesinin karşılığı; yalnız no tutulur).
-- surum: şartname ve sürümlerindeki her komutun iyimser kilidi.
CREATE TABLE rota_islem_sartnamesi (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kod text NOT NULL CONSTRAINT rota_islem_sartnamesi_kod_bicimi CHECK (kod ~ '^[A-Z0-9][A-Z0-9-]{1,29}$'),
  kategori_id int NOT NULL CONSTRAINT rota_islem_sartnamesi_kategori_bagi REFERENCES rota_islem_kategorisi (id),
  ad text NOT NULL CONSTRAINT rota_islem_sartnamesi_ad_dolu CHECK (btrim(ad) <> '' AND length(ad) <= 120),
  kapsam text NOT NULL CONSTRAINT rota_islem_sartnamesi_kapsam_gecerli CHECK (kapsam IN ('ic', 'fason', 'ikisi')),
  kaynak text NOT NULL CONSTRAINT rota_islem_sartnamesi_kaynak_gecerli CHECK (kaynak IN ('varsayilan', 'firma', 'musteri')),
  musteri_firma_id int CONSTRAINT rota_islem_sartnamesi_musteri_bagi REFERENCES musteri_tedarikci_firma (id),
  musteri_belge_no text CONSTRAINT rota_islem_sartnamesi_belge_no_dolu CHECK (musteri_belge_no IS NULL OR (btrim(musteri_belge_no) <> '' AND length(musteri_belge_no) <= 60)),
  aktif boolean NOT NULL DEFAULT true,
  surum int NOT NULL DEFAULT 1 CONSTRAINT rota_islem_sartnamesi_surum_pozitif CHECK (surum > 0),
  CONSTRAINT rota_islem_sartnamesi_kod_tekil UNIQUE (kod),
  CONSTRAINT rota_islem_sartnamesi_musteri_tutarli CHECK ((kaynak = 'musteri') = (musteri_firma_id IS NOT NULL AND musteri_belge_no IS NOT NULL))
);
CREATE INDEX rota_islem_sartnamesi_kategori_fk_idx ON rota_islem_sartnamesi (kategori_id);
CREATE INDEX rota_islem_sartnamesi_musteri_fk_idx ON rota_islem_sartnamesi (musteri_firma_id) WHERE musteri_firma_id IS NOT NULL;

-- Şartname başına en çok bir yürürlükte ve bir taslak sürüm. Yürürlükteki ve eski sürüm değişmez (aşağıdaki tetikleyici);
-- yalnız yürürlükteki sürüm "eski"ye geçebilir.
CREATE TABLE rota_islem_sartnamesi_surumu (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sartname_id int NOT NULL CONSTRAINT rota_islem_sartnamesi_surumu_sartname_bagi REFERENCES rota_islem_sartnamesi (id),
  surum_no int NOT NULL CONSTRAINT rota_islem_sartnamesi_surumu_no_pozitif CHECK (surum_no > 0),
  durum text NOT NULL CONSTRAINT rota_islem_sartnamesi_surumu_durum_gecerli CHECK (durum IN ('taslak', 'yururlukte', 'eski')),
  istenen_belgeler text[] NOT NULL DEFAULT '{}' CONSTRAINT rota_islem_sartnamesi_surumu_belge_sayisi CHECK (cardinality(istenen_belgeler) <= 20),
  terminal_notu text CONSTRAINT rota_islem_sartnamesi_surumu_not_boyu CHECK (terminal_notu IS NULL OR (btrim(terminal_notu) <> '' AND length(terminal_notu) <= 1000)),
  degisiklik_notu text CONSTRAINT rota_islem_sartnamesi_surumu_degisiklik_boyu CHECK (degisiklik_notu IS NULL OR (btrim(degisiklik_notu) <> '' AND length(degisiklik_notu) <= 500)),
  acan_kisi_id int CONSTRAINT rota_islem_sartnamesi_surumu_acan_bagi REFERENCES kisi (id),
  acilma timestamptz NOT NULL DEFAULT now(),
  yayinlayan_kisi_id int CONSTRAINT rota_islem_sartnamesi_surumu_yayinlayan_bagi REFERENCES kisi (id),
  yayin timestamptz,
  CONSTRAINT rota_islem_sartnamesi_surumu_no_tekil UNIQUE (sartname_id, surum_no),
  CONSTRAINT rota_islem_sartnamesi_surumu_yayin_tutarli CHECK ((durum = 'taslak') = (yayin IS NULL))
);
CREATE UNIQUE INDEX rota_islem_sartnamesi_surumu_tek_yururlukte ON rota_islem_sartnamesi_surumu (sartname_id) WHERE durum = 'yururlukte';
CREATE UNIQUE INDEX rota_islem_sartnamesi_surumu_tek_taslak ON rota_islem_sartnamesi_surumu (sartname_id) WHERE durum = 'taslak';
CREATE INDEX rota_islem_sartnamesi_surumu_acan_fk_idx ON rota_islem_sartnamesi_surumu (acan_kisi_id) WHERE acan_kisi_id IS NOT NULL;
CREATE INDEX rota_islem_sartnamesi_surumu_yayinlayan_fk_idx ON rota_islem_sartnamesi_surumu (yayinlayan_kisi_id) WHERE yayinlayan_kisi_id IS NOT NULL;

-- Parametre şablonu. Değer türleri: sayi (sayı), aralik ([alt, üst]), secim (seceneklerden biri), coklu (seceneklerden alt küme),
-- metin, evet (doğru/yanlış). adimda_degisir: değeri rota adımı verir; değilse şablondaki varsayılan sabittir.
CREATE TABLE rota_islem_sartnamesi_parametresi (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  surum_id int NOT NULL CONSTRAINT rota_islem_sartnamesi_parametresi_surum_bagi REFERENCES rota_islem_sartnamesi_surumu (id),
  sira int NOT NULL CONSTRAINT rota_islem_sartnamesi_parametresi_sira_pozitif CHECK (sira > 0),
  anahtar text NOT NULL CONSTRAINT rota_islem_sartnamesi_parametresi_anahtar_bicimi CHECK (anahtar ~ '^[a-z][a-zA-Z0-9]{0,39}$'),
  ad text NOT NULL CONSTRAINT rota_islem_sartnamesi_parametresi_ad_dolu CHECK (btrim(ad) <> '' AND length(ad) <= 80),
  tur text NOT NULL CONSTRAINT rota_islem_sartnamesi_parametresi_tur_gecerli CHECK (tur IN ('sayi', 'aralik', 'secim', 'coklu', 'metin', 'evet')),
  birim text CONSTRAINT rota_islem_sartnamesi_parametresi_birim_boyu CHECK (birim IS NULL OR (btrim(birim) <> '' AND length(birim) <= 20)),
  secenekler text[] CONSTRAINT rota_islem_sartnamesi_parametresi_secenek_tutarli
    CHECK ((tur IN ('secim', 'coklu')) = (secenekler IS NOT NULL AND cardinality(secenekler) BETWEEN 1 AND 30)),
  varsayilan jsonb,
  ipucu text CONSTRAINT rota_islem_sartnamesi_parametresi_ipucu_boyu CHECK (ipucu IS NULL OR (btrim(ipucu) <> '' AND length(ipucu) <= 120)),
  zorunlu boolean NOT NULL,
  adimda_degisir boolean NOT NULL,
  CONSTRAINT rota_islem_sartnamesi_parametresi_anahtar_tekil UNIQUE (surum_id, anahtar),
  CONSTRAINT rota_islem_sartnamesi_parametresi_sira_tekil UNIQUE (surum_id, sira)
);

CREATE TABLE rota_islem_sartnamesi_atfi (
  surum_id int NOT NULL CONSTRAINT rota_islem_sartnamesi_atfi_surum_bagi REFERENCES rota_islem_sartnamesi_surumu (id),
  sira int NOT NULL CONSTRAINT rota_islem_sartnamesi_atfi_sira_pozitif CHECK (sira > 0),
  standart_id int NOT NULL CONSTRAINT rota_islem_sartnamesi_atfi_standart_bagi REFERENCES rota_standart_atfi (id),
  rol text NOT NULL CONSTRAINT rota_islem_sartnamesi_atfi_rol_gecerli CHECK (rol IN ('yontem', 'kabul', 'test', 'olcum', 'malzeme', 'gosterim')),
  "not" text CONSTRAINT rota_islem_sartnamesi_atfi_not_boyu CHECK ("not" IS NULL OR (btrim("not") <> '' AND length("not") <= 120)),
  PRIMARY KEY (surum_id, sira),
  CONSTRAINT rota_islem_sartnamesi_atfi_tekil UNIQUE (surum_id, standart_id, rol)
);
CREATE INDEX rota_islem_sartnamesi_atfi_standart_fk_idx ON rota_islem_sartnamesi_atfi (standart_id);

-- Yürürlükteki ve eski sürüm, parametreleri ve atıflarıyla değişmez: emre sabitlenen sürüm sonradan oynamaz. Tek izinli değişiklik
-- yürürlükteki sürümün "eski"ye geçmesidir (yeni sürüm yayınlanınca).
CREATE FUNCTION rota_sartname_surumu_kilitli() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  durum text;
  surum int;
BEGIN
  IF TG_TABLE_NAME = 'rota_islem_sartnamesi_surumu' THEN
    IF TG_OP = 'INSERT' THEN RETURN NEW; END IF;
    IF OLD.durum = 'taslak' THEN
      IF TG_OP = 'UPDATE' AND NEW.sartname_id <> OLD.sartname_id THEN
        RAISE EXCEPTION 'Sürüm başka şartnameye taşınmaz' USING ERRCODE = 'check_violation', CONSTRAINT = 'rota_sartname_surumu_kilitli';
      END IF;
      IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
      RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.durum = 'yururlukte' AND NEW.durum = 'eski'
       AND (NEW.sartname_id, NEW.surum_no, NEW.istenen_belgeler, NEW.terminal_notu, NEW.degisiklik_notu, NEW.acan_kisi_id, NEW.acilma, NEW.yayinlayan_kisi_id, NEW.yayin)
         IS NOT DISTINCT FROM (OLD.sartname_id, OLD.surum_no, OLD.istenen_belgeler, OLD.terminal_notu, OLD.degisiklik_notu, OLD.acan_kisi_id, OLD.acilma, OLD.yayinlayan_kisi_id, OLD.yayin) THEN
      RETURN NEW;
    END IF;
    RAISE EXCEPTION 'Yayınlanmış şartname sürümü değişmez (sürüm %)', OLD.id USING ERRCODE = 'check_violation', CONSTRAINT = 'rota_sartname_surumu_kilitli';
  END IF;
  IF TG_OP = 'DELETE' THEN surum := OLD.surum_id; ELSE surum := NEW.surum_id; END IF;
  SELECT v.durum INTO durum FROM rota_islem_sartnamesi_surumu v WHERE v.id = surum;
  IF durum IS DISTINCT FROM 'taslak' OR (TG_OP = 'UPDATE' AND NEW.surum_id <> OLD.surum_id) THEN
    RAISE EXCEPTION 'Şartname içeriği yalnız taslak sürümde değişir (sürüm %)', surum
      USING ERRCODE = 'check_violation', CONSTRAINT = 'rota_sartname_surumu_kilitli', TABLE = TG_TABLE_NAME;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER rota_islem_sartnamesi_surumu_kilitli BEFORE INSERT OR UPDATE OR DELETE ON rota_islem_sartnamesi_surumu
  FOR EACH ROW EXECUTE FUNCTION rota_sartname_surumu_kilitli();
CREATE TRIGGER rota_islem_sartnamesi_parametresi_kilitli BEFORE INSERT OR UPDATE OR DELETE ON rota_islem_sartnamesi_parametresi
  FOR EACH ROW EXECUTE FUNCTION rota_sartname_surumu_kilitli();
CREATE TRIGGER rota_islem_sartnamesi_atfi_kilitli BEFORE INSERT OR UPDATE OR DELETE ON rota_islem_sartnamesi_atfi
  FOR EACH ROW EXECUTE FUNCTION rota_sartname_surumu_kilitli();

-- Rota adımının şartnameleri. Adım kaydı bütün olarak silinip yeniden yazıldığı için bağ adım kimliğine değil revizyon ve OP numarasına
-- verilir; yabancı anahtar ertelenir, aynı işlemde yeniden yazılan adım bağı korur. Sürüm değil şartname seçilir: emir açılırken
-- yürürlükteki sürüm sabitlenir (971 a).
CREATE TABLE rota_adim_sartnamesi (
  revizyon_id int NOT NULL,
  op_no int NOT NULL,
  sira int NOT NULL CONSTRAINT rota_adim_sartnamesi_sira_pozitif CHECK (sira > 0),
  sartname_id int NOT NULL CONSTRAINT rota_adim_sartnamesi_sartname_bagi REFERENCES rota_islem_sartnamesi (id),
  degerler jsonb NOT NULL DEFAULT '{}' CONSTRAINT rota_adim_sartnamesi_degerler_nesne CHECK (jsonb_typeof(degerler) = 'object'),
  PRIMARY KEY (revizyon_id, op_no, sira),
  CONSTRAINT rota_adim_sartnamesi_tekil UNIQUE (revizyon_id, op_no, sartname_id),
  CONSTRAINT rota_adim_sartnamesi_adim_bagi FOREIGN KEY (revizyon_id, op_no) REFERENCES rota_adimi (revizyon_id, op_no) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX rota_adim_sartnamesi_sartname_fk_idx ON rota_adim_sartnamesi (sartname_id);

-- Bağ yalnız taslak revizyonda yazılır ve silinir (rota içeriğiyle aynı kural).
CREATE FUNCTION rota_adim_sartnamesi_kilitli() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  satir record;
  durum text;
BEGIN
  IF TG_OP = 'DELETE' THEN satir := OLD; ELSE satir := NEW; END IF;
  IF TG_OP = 'UPDATE' AND NEW.revizyon_id <> OLD.revizyon_id THEN
    RAISE EXCEPTION 'Şartname bağı başka revizyona taşınmaz' USING ERRCODE = 'check_violation', CONSTRAINT = 'rota_icerik_kilitli';
  END IF;
  SELECT r.durum INTO durum FROM rota_revizyonu r WHERE r.id = satir.revizyon_id;
  IF durum IS DISTINCT FROM 'taslak' THEN
    RAISE EXCEPTION 'Rota içeriği yalnız taslakta değişir (revizyon %, durum %)', satir.revizyon_id, durum
      USING ERRCODE = 'check_violation', CONSTRAINT = 'rota_icerik_kilitli', TABLE = TG_TABLE_NAME;
  END IF;
  RETURN satir;
END $$;
CREATE TRIGGER rota_adim_sartnamesi_kilitli BEFORE INSERT OR UPDATE OR DELETE ON rota_adim_sartnamesi
  FOR EACH ROW EXECUTE FUNCTION rota_adim_sartnamesi_kilitli();

