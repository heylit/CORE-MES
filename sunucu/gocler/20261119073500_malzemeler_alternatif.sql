-- 3437: İkame ve alternatifler. Kalite ve durum muadilleri ile alternatif kuralları (aile, sınıf, kalite ya da tek kart) sunucuda tutulur;
-- motor bir kartın kabul zarfını bunlardan hesaplar. Yalnız ekleyen göç; kalite muadillerinin ilk içeriği katalog ekranındaki listedir.

CREATE TABLE malzeme_kalite_muadili (
  kalite text NOT NULL CONSTRAINT malzeme_kalite_muadili_kalite_dolu CHECK (btrim(kalite) <> '' AND length(kalite) <= 40),
  muadil text NOT NULL CONSTRAINT malzeme_kalite_muadili_muadil_dolu CHECK (btrim(muadil) <> '' AND length(muadil) <= 40),
  tur text NOT NULL CONSTRAINT malzeme_kalite_muadili_tur CHECK (tur IN ('tam', 'ust', 'sartli')),
  notu text CONSTRAINT malzeme_kalite_muadili_not CHECK (notu IS NULL OR (btrim(notu) <> '' AND length(notu) <= 300)),
  surum int NOT NULL DEFAULT 1,
  guncelleyen_kisi_id int REFERENCES kisi,
  guncelleme timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (kalite, muadil),
  CONSTRAINT malzeme_kalite_muadili_kendisi CHECK (kalite <> muadil)
);

CREATE TABLE malzeme_durum_muadili (
  durum text NOT NULL CONSTRAINT malzeme_durum_muadili_durum_dolu CHECK (btrim(durum) <> '' AND length(durum) <= 60),
  muadil text NOT NULL CONSTRAINT malzeme_durum_muadili_muadil_dolu CHECK (btrim(muadil) <> '' AND length(muadil) <= 60),
  tur text NOT NULL CONSTRAINT malzeme_durum_muadili_tur CHECK (tur IN ('tam', 'ust', 'sartli')),
  notu text CONSTRAINT malzeme_durum_muadili_not CHECK (notu IS NULL OR (btrim(notu) <> '' AND length(notu) <= 300)),
  surum int NOT NULL DEFAULT 1,
  guncelleyen_kisi_id int REFERENCES kisi,
  guncelleme timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (durum, muadil),
  CONSTRAINT malzeme_durum_muadili_kendisi CHECK (durum <> muadil)
);

-- Boş alan "üst kapsamdan miras" demektir; dar kapsam (kart < kalite < sınıf < aile) geniş olanı ezer. Kart kapsamı kartın sayı kimliğidir.
CREATE TABLE malzeme_alternatif_kurali (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kapsam_turu text NOT NULL CONSTRAINT malzeme_alternatif_kurali_kapsam_turu CHECK (kapsam_turu IN ('aile', 'sinif', 'kalite', 'kart')),
  kapsam text NOT NULL CONSTRAINT malzeme_alternatif_kurali_kapsam_dolu CHECK (btrim(kapsam) = kapsam AND kapsam <> '' AND length(kapsam) <= 64),
  kalite_acik boolean,
  durum_acik boolean,
  sartli_acik boolean,
  boy_uzun_kesilir boolean,
  yuzey_serbest boolean,
  pay_turu text CONSTRAINT malzeme_alternatif_kurali_pay_turu CHECK (pay_turu IN ('tam', 'mm', 'yuzde')),
  pay_deger numeric(8, 3) CONSTRAINT malzeme_alternatif_kurali_pay_deger CHECK (pay_deger >= 0 AND pay_deger <= 1000),
  pay_en_az_mm numeric(8, 3) CONSTRAINT malzeme_alternatif_kurali_pay_en_az CHECK (pay_en_az_mm >= 0 AND pay_en_az_mm <= 1000),
  kapali boolean,
  gerekce text CONSTRAINT malzeme_alternatif_kurali_gerekce_dolu CHECK (gerekce IS NULL OR (btrim(gerekce) <> '' AND length(gerekce) <= 300)),
  surum int NOT NULL DEFAULT 1,
  guncelleyen_kisi_id int NOT NULL REFERENCES kisi,
  guncelleme timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT malzeme_alternatif_kurali_kapsam_tek UNIQUE (kapsam_turu, kapsam),
  CONSTRAINT malzeme_alternatif_kurali_kart_no CHECK (kapsam_turu <> 'kart' OR kapsam ~ '^[1-9][0-9]{0,9}$'),
  CONSTRAINT malzeme_alternatif_kurali_pay_butun CHECK (
    (pay_turu IS NULL AND pay_deger IS NULL AND pay_en_az_mm IS NULL)
    OR (pay_turu = 'tam' AND pay_deger IS NULL AND pay_en_az_mm IS NULL)
    OR (pay_turu = 'mm' AND pay_deger IS NOT NULL AND pay_en_az_mm IS NULL)
    OR (pay_turu = 'yuzde' AND pay_deger IS NOT NULL)),
  CONSTRAINT malzeme_alternatif_kurali_kapali_gerekceli CHECK (kapali IS NOT TRUE OR gerekce IS NOT NULL)
);

